#!/usr/bin/env python3
"""
generate_collections_reference.py
Renders docs/reference/collections.md from _config.yml, so the site's content
model is read from the config Jekyll actually uses instead of a hand-copied table.

For every collection declared under `collections:` it lists the directory
(`<collections_dir>/_<name>`), whether that directory exists, `output`, the
permalink pattern, and the `layout` and `sidebar.nav` that the front-matter
`defaults:` give a file there. Defaults are resolved the way Jekyll does: every
entry whose `scope.path` is a prefix of the directory (and whose `scope.type`,
if set, names the collection) applies, the more specific one winning.

Usage:
  python3 scripts/generate_collections_reference.py           # rewrite the reference
  python3 scripts/generate_collections_reference.py --check   # exit 1 if it is stale

Stdlib + PyYAML (scripts/requirements.txt). Deterministic: collections render in
_config.yml order, so a rerun with no config change writes nothing.
"""

import argparse
import os
import sys
from typing import Dict, List

import yaml

REPO_ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
CONFIG_FILE = os.path.join(REPO_ROOT, '_config.yml')
OUTPUT_FILE = os.path.join(REPO_ROOT, 'docs', 'reference', 'collections.md')
COMMAND = 'python3 scripts/generate_collections_reference.py'


class _JekyllLoader(yaml.SafeLoader):
    """SafeLoader that reads an alias with no anchor as null, the way the site build does.

    _config.yml uses `*site_domain` without ever defining `&site_domain`; Jekyll's
    YAML parser accepts that and PyYAML's raises ComposerError.
    """

    def compose_node(self, parent, index):
        if self.check_event(yaml.AliasEvent):
            event = self.peek_event()
            if event.anchor not in self.anchors:
                self.get_event()
                return yaml.ScalarNode('tag:yaml.org,2002:null', '', event.start_mark, event.end_mark)
        return super().compose_node(parent, index)


def load_config(path: str = CONFIG_FILE) -> dict:
    with open(path, encoding='utf-8') as fh:
        return yaml.load(fh, Loader=_JekyllLoader) or {}  # noqa: S506 - SafeLoader subclass


def _deep_merge(base: dict, over: dict) -> dict:
    out = dict(base)
    for key, value in over.items():
        if isinstance(value, dict) and isinstance(out.get(key), dict):
            out[key] = _deep_merge(out[key], value)
        else:
            out[key] = value
    return out


def _applies(scope: dict, directory: str, collection: str) -> bool:
    path = str(scope.get('path', '') or '').strip('/')
    if path and directory != path and not directory.startswith(path + '/'):
        return False
    kind = scope.get('type')
    return not kind or kind == collection


def resolve_defaults(defaults: List[dict], directory: str, collection: str) -> dict:
    """Front-matter defaults a file in `directory` of `collection` receives."""
    matching = []
    for index, entry in enumerate(defaults or []):
        scope = (entry or {}).get('scope') or {}
        if _applies(scope, directory, collection):
            path = str(scope.get('path', '') or '').strip('/')
            matching.append((len(path), 1 if scope.get('type') else 0, index, entry.get('values') or {}))
    values: dict = {}
    for *_rank, entry_values in sorted(matching, key=lambda m: m[:3]):
        values = _deep_merge(values, entry_values)
    return values


def collection_rows(config: dict, root: str = REPO_ROOT) -> List[Dict[str, str]]:
    base = str(config.get('collections_dir', '') or '').strip('/')
    rows = []
    for name, spec in (config.get('collections') or {}).items():
        spec = spec or {}
        directory = f'{base}/_{name}' if base else f'_{name}'
        values = resolve_defaults(config.get('defaults') or [], directory, name)
        sidebar = values.get('sidebar') or {}
        rows.append({
            'collection': name,
            'directory': directory,
            'exists': 'yes' if os.path.isdir(os.path.join(root, directory)) else 'no',
            'output': 'yes' if spec.get('output') else 'no',
            'permalink': str(spec.get('permalink') or config.get('permalink') or ''),
            'layout': str(values.get('layout') or ''),
            'sidebar': str(sidebar.get('nav') or '') if isinstance(sidebar, dict) else '',
        })
    return rows


def _code(value: str) -> str:
    return f'`{value}`' if value else '—'


def render(config: dict, root: str = REPO_ROOT) -> str:
    lines = [
        f'<!-- GENERATED by {COMMAND} — do not edit by hand -->',
        '# Collections reference',
        '',
        '> Every Jekyll collection `_config.yml` declares — its directory, permalink, and the layout and sidebar its front-matter defaults give it — generated from the config.',
        '',
        f'Source: `_config.yml` (`collections_dir`, `collections:`, `defaults:`). '
        f'Regenerate with `{COMMAND}`; `--check` exits 1 when this file is stale. '
        'A collection whose directory does not exist is declared but has no content yet.',
        '',
        '| Collection | Directory | Exists | Output | Permalink | Default layout | Sidebar nav |',
        '| --- | --- | --- | --- | --- | --- | --- |',
    ]
    for row in collection_rows(config, root):
        lines.append(
            f"| `{row['collection']}` | {_code(row['directory'] + '/')} | {row['exists']} | {row['output']} "
            f"| {_code(row['permalink'])} | {_code(row['layout'])} | {_code(row['sidebar'])} |"
        )
    return '\n'.join(lines) + '\n'


def is_current(path: str = OUTPUT_FILE, config_path: str = CONFIG_FILE) -> bool:
    want = render(load_config(config_path))
    try:
        with open(path, encoding='utf-8') as fh:
            return fh.read() == want
    except FileNotFoundError:
        return False


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description='Render docs/reference/collections.md from _config.yml.')
    parser.add_argument('--check', action='store_true', help='exit 1 if the reference is stale; write nothing')
    args = parser.parse_args(argv)

    if args.check:
        if is_current():
            print('docs/reference/collections.md is current')
            return 0
        print(f'docs/reference/collections.md is stale — run: {COMMAND}', file=sys.stderr)
        return 1

    text = render(load_config())
    os.makedirs(os.path.dirname(OUTPUT_FILE), exist_ok=True)
    try:
        with open(OUTPUT_FILE, encoding='utf-8') as fh:
            if fh.read() == text:
                print('docs/reference/collections.md unchanged')
                return 0
    except FileNotFoundError:
        pass
    with open(OUTPUT_FILE, 'w', encoding='utf-8') as fh:
        fh.write(text)
    print('wrote docs/reference/collections.md')
    return 0


if __name__ == '__main__':
    sys.exit(main())
