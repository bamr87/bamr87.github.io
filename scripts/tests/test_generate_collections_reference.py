"""Tests for the collections reference generator (docs/reference/collections.md).

Run from the repo root: python -m pytest -q scripts/tests
"""

from scripts.generate_collections_reference import (
    COMMAND,
    is_current,
    load_config,
    render,
    resolve_defaults,
)


def test_committed_reference_is_current():
    # The drift gate: editing _config.yml collections or defaults without
    # regenerating fails here. Fix with: python3 scripts/generate_collections_reference.py
    assert is_current(), f'docs/reference/collections.md is stale — run: {COMMAND}'


def test_most_specific_default_wins():
    defaults = [
        {'scope': {'path': ''}, 'values': {'layout': 'root', 'sidebar': {'nav': 'main'}}},
        {'scope': {'path': 'pages'}, 'values': {'layout': 'default'}},
        {'scope': {'path': 'pages/_posts'}, 'values': {'layout': 'article', 'sidebar': {'nav': 'dynamic'}}},
    ]
    assert resolve_defaults(defaults, 'pages/_posts', 'posts') == {'layout': 'article', 'sidebar': {'nav': 'dynamic'}}
    assert resolve_defaults(defaults, 'pages/_docs', 'docs') == {'layout': 'default', 'sidebar': {'nav': 'main'}}


def test_type_scope_only_matches_its_collection():
    defaults = [{'scope': {'path': 'pages/_notes', 'type': 'notes'}, 'values': {'share': False}}]
    assert resolve_defaults(defaults, 'pages/_notes', 'notes') == {'share': False}
    assert resolve_defaults(defaults, 'pages/_notes', 'posts') == {}


def test_path_prefix_matches_whole_segments():
    defaults = [{'scope': {'path': 'pages/_doc'}, 'values': {'layout': 'x'}}]
    assert resolve_defaults(defaults, 'pages/_docs', 'docs') == {}


def test_render_opens_with_generated_marker_and_lists_every_collection():
    config = load_config()
    text = render(config)
    assert text.startswith('<!-- GENERATED by ')
    for name in config['collections']:
        assert f'| `{name}` |' in text
